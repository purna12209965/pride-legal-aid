// Helper function to find best matching response
export function findBestResponse(userMessage: string): string {
  const lowerMessage = userMessage.toLowerCase();
  
  // Score each knowledge entry based on keyword matches
  const scores: { entry: KnowledgeEntry; score: number }[] = [];
  
  for (const entry of chatbotKnowledge) {
    let score = 0;
    
    // Skip the default/general and fallback responses for now
    if (entry.category === 'general' || entry.category === 'fallback') {
      continue;
    }
    
    // Check each keyword
    for (const keyword of entry.keywords) {
      if (lowerMessage.includes(keyword.toLowerCase())) {
        // Longer keywords get higher scores (more specific)
        score += keyword.length;
      }
    }
    
    if (score > 0) {
      scores.push({ entry, score });
    }
  }
  
  // Sort by score (highest first)
  scores.sort((a, b) => b.score - a.score);
  
  // Return highest scoring response
  if (scores.length > 0) {
    return scores[0].entry.response;
  }
  
  // Check if it's a greeting
  const greetingKeywords = ['hello', 'hi', 'hey', 'help', 'what can you do', 'who are you'];
  for (const keyword of greetingKeywords) {
    if (lowerMessage.includes(keyword)) {
      const defaultEntry = chatbotKnowledge.find(e => e.category === 'general');
      return defaultEntry?.response || "Hello! How can I help you with LGBTQ+ legal questions?";
    }
  }
  
  // Return fallback response if no specific match
  const fallbackEntry = chatbotKnowledge.find(e => e.category === 'fallback');
  return fallbackEntry?.response || "I'm here to help with LGBTQ+ legal questions. Could you rephrase your question or ask about a specific legal issue?";
}
